create extension if not exists pg_net with schema extensions;
create extension if not exists pg_cron;

create table if not exists public.manager_push_queue (
  id bigint generated by default as identity primary key,
  event_type text not null check (event_type in ('new_order', 'call_message', 'supplier_update', 'quote_approval', 'delivery_update', 'test')),
  title text not null,
  body text not null,
  href text not null,
  tag text,
  dedupe_key text not null unique,
  attempts integer not null default 0 check (attempts >= 0),
  available_at timestamptz not null default now(),
  processed_at timestamptz,
  last_error text,
  created_at timestamptz not null default now()
);

create index if not exists manager_push_queue_pending_idx
  on public.manager_push_queue(available_at, created_at)
  where processed_at is null and attempts < 5;

alter table public.manager_push_queue enable row level security;
revoke all on table public.manager_push_queue from anon, authenticated;

do $$
begin
  if not exists (select 1 from vault.secrets where name = 'manager_push_dispatch_secret') then
    perform vault.create_secret(
      encode(extensions.gen_random_bytes(32), 'hex'),
      'manager_push_dispatch_secret',
      'Authenticates scheduled Avantia manager push delivery'
    );
  end if;

  if not exists (select 1 from vault.secrets where name = 'project_url') then
    perform vault.create_secret(
      'https://nprfhspwdflpqlopydmp.supabase.co',
      'project_url',
      'Avantia Build Supabase project URL for scheduled Edge Functions'
    );
  end if;
end;
$$;

create or replace function public.get_manager_push_dispatch_secret()
returns text
language sql
security definer
set search_path = ''
stable
as $$
  select decrypted_secret
  from vault.decrypted_secrets
  where name = 'manager_push_dispatch_secret'
  limit 1;
$$;

revoke all on function public.get_manager_push_dispatch_secret() from public, anon, authenticated;
grant execute on function public.get_manager_push_dispatch_secret() to service_role;

create or replace function public.claim_manager_push_events(p_limit integer default 25)
returns table (
  id bigint,
  event_type text,
  title text,
  body text,
  href text,
  tag text
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  return query
  with claimed as (
    select queue.id
    from public.manager_push_queue as queue
    where queue.processed_at is null
      and queue.attempts < 5
      and queue.available_at <= now()
    order by queue.created_at
    for update skip locked
    limit least(greatest(coalesce(p_limit, 25), 1), 100)
  ), updated as (
    update public.manager_push_queue as queue
    set attempts = queue.attempts + 1,
        available_at = now() + interval '5 minutes'
    from claimed
    where queue.id = claimed.id
    returning queue.id, queue.event_type, queue.title, queue.body, queue.href, queue.tag
  )
  select updated.id, updated.event_type, updated.title, updated.body, updated.href, updated.tag
  from updated;
end;
$$;

revoke all on function public.claim_manager_push_events(integer) from public, anon, authenticated;
grant execute on function public.claim_manager_push_events(integer) to service_role;

create or replace function public.queue_manager_push_event(
  p_event_type text,
  p_title text,
  p_body text,
  p_href text,
  p_dedupe_key text,
  p_tag text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_event_type not in ('new_order', 'call_message', 'supplier_update', 'quote_approval', 'delivery_update') then
    raise exception 'Unsupported manager push event';
  end if;

  insert into public.manager_push_queue (event_type, title, body, href, dedupe_key, tag)
  values (
    p_event_type,
    left(coalesce(nullif(trim(p_title), ''), 'Avantia update'), 160),
    left(coalesce(nullif(trim(p_body), ''), 'Open Avantia for details.'), 500),
    case when p_href like '/%' then left(p_href, 500) else '/admin/build-map' end,
    left(p_dedupe_key, 240),
    left(p_tag, 120)
  )
  on conflict (dedupe_key) do nothing;
end;
$$;

revoke all on function public.queue_manager_push_event(text, text, text, text, text, text) from public, anon, authenticated;

create or replace function public.queue_new_request_push()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.status <> 'draft' and (tg_op = 'INSERT' or old.status = 'draft') then
    perform public.queue_manager_push_event(
      'new_order',
      'New material request',
      coalesce(new.title, 'A customer submitted a material request.'),
      '/owner/materials/requests/' || new.id::text,
      'new_order:' || new.id::text,
      'avantia-new-order-' || new.id::text
    );
  end if;
  return new;
end;
$$;

