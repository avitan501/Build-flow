create or replace function public.dispatch_manager_push_queue()
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  project_url text;
  dispatch_secret text;
  request_id bigint;
begin
  if not exists (
    select 1 from public.manager_push_queue
    where processed_at is null and attempts < 5 and available_at <= now()
  ) then return null; end if;

  select decrypted_secret into project_url from vault.decrypted_secrets where name = 'project_url' limit 1;
  select decrypted_secret into dispatch_secret from vault.decrypted_secrets where name = 'manager_push_dispatch_secret' limit 1;
  if project_url is null or dispatch_secret is null then return null; end if;

  select net.http_post(
    url := project_url || '/functions/v1/manager-web-push',
    headers := jsonb_build_object('Content-Type', 'application/json', 'X-Manager-Push-Dispatch', dispatch_secret),
    body := jsonb_build_object('action', 'deliver_queue'),
    timeout_milliseconds := 15000
  ) into request_id;
  return request_id;
end;
$$;

revoke all on function public.dispatch_manager_push_queue() from public, anon, authenticated;

do $$
declare
  existing_job bigint;
begin
  select jobid into existing_job from cron.job where jobname = 'dispatch-manager-web-push' limit 1;
  if existing_job is not null then perform cron.unschedule(existing_job); end if;
  perform cron.schedule('dispatch-manager-web-push', '* * * * *', 'select public.dispatch_manager_push_queue();');
end;
$$;
