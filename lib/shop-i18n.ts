function translatePattern(value: string) {
  let match = value.match(/^Need Help With a Custom (.+) Order\?$/)
  if (match) return `¿Necesita ayuda con un pedido personalizado de ${translateShopText(match[1], "es").toLowerCase()}?`

  match = value.match(/^Confirm This (.+) Request$/)
  if (match) return `Confirmar solicitud de ${translateShopText(match[1], "es").toLowerCase()}`

  match = value.match(/^Loading (.+) order$/)
  if (match) return `Cargando pedido de ${translateShopText(match[1], "es").toLowerCase()}`

  match = value.match(/^Reference attached: (.+)$/)
  if (match) return `Referencia adjunta: ${match[1]}`

  match = value.match(/^Your (.+) request was created\. Someone from Avantia Build will get back to you within 24 hours\.$/)
  if (match) return `Su solicitud de ${translateShopText(match[1], "es").toLowerCase()} fue creada. Alguien de Avantia Build le responderá dentro de 24 horas.`

  match = value.match(/^Please answer: (.+)$/)
  if (match) return `Responda: ${translateShopText(match[1], "es")}`

  match = value.match(/^(\d+)\/(\d+) required fields · optional details excluded$/)
  if (match) return `${match[1]}/${match[2]} campos obligatorios · no incluye detalles opcionales`

  match = value.match(/^(\d+)\/(\d+) required fields$/)
  if (match) return `${match[1]}/${match[2]} campos obligatorios`

  match = value.match(/^(\d+) questions$/)
  if (match) return `${match[1]} preguntas`

  match = value.match(/^Question (\d+) of (\d+)$/)
  if (match) return `Pregunta ${match[1]} de ${match[2]}`

  match = value.match(/^Question (\d+)$/)
  if (match) return `Pregunta ${match[1]}`

  match = value.match(/^(\d+) selections$/)
  if (match) return `${match[1]} selecciones`

  match = value.match(/^\+(\d+) more in review$/)
  if (match) return `+${match[1]} más en la revisión`

  match = value.match(/^(\d+) items ready to browse$/)
  if (match) return `${match[1]} ${match[1] === "1" ? "artículo listo" : "artículos listos"} para ver`

  match = value.match(/^(\d+) item(s?)$/)
  if (match) return `${match[1]} artículo${match[1] === "1" ? "" : "s"}`

  match = value.match(/^Search results for "(.+)"$/)
  if (match) return `Resultados de búsqueda para “${match[1]}”`

  match = value.match(/^Showing only (.+) items\. Use the section buttons above to switch focus\.$/)
  if (match) return `Mostrando solo artículos de ${translateShopText(match[1], "es")}. Use los botones de arriba para cambiar de sección.`

  match = value.match(/^Browse (.+) materials$/)
  if (match) return `Ver materiales de ${translateShopText(match[1], "es").toLowerCase()}`

  match = value.match(/^(.+) tools$/)
  if (match) return `Herramientas de ${translateShopText(match[1], "es").toLowerCase()}`

  match = value.match(/^View all ([\d,]+) projects$/)
  if (match) return `Ver los ${match[1]} proyectos`

  match = value.match(/^Address found: (.+)\. Saving project\.\.\.$/)
  if (match) return `Dirección encontrada: ${match[1]}. Guardando proyecto...`

  match = value.match(/^Decrease (.+)$/)
  if (match) return `Disminuir ${translateShopText(match[1], "es").toLowerCase()}`

  match = value.match(/^Increase (.+)$/)
  if (match) return `Aumentar ${translateShopText(match[1], "es").toLowerCase()}`

  match = value.match(/^(.+) quantity$/)
  if (match) return `Cantidad de ${translateShopText(match[1], "es").toLowerCase()}`

  match = value.match(/^(.+) Quick Order$/)
  if (match) return `Pedido rápido de ${translateShopText(match[1], "es").toLowerCase()}`

  match = value.match(/^(.+) image$/)
  if (match) return `Imagen de ${translateShopText(match[1], "es").toLowerCase()}`

  match = value.match(/^Remove (molding|cable|lumber) item (\d+)$/)
  if (match) {
    const item = match[1] === "molding" ? "moldura" : match[1] === "cable" ? "cable" : "madera"
    return `Eliminar artículo de ${item} ${match[2]}`
  }

  match = value.match(/^(\d+) files? attached$/)
  if (match) return `${match[1]} archivo${match[1] === "1" ? "" : "s"} adjunto${match[1] === "1" ? "" : "s"}`

  match = value.match(/^(Each|Sheet|Box|Tube|Roll|Bag|Bucket) - (.+)$/)
  if (match) return `${translateShopText(match[1], "es")} - ${match[2]}`

  match = value.match(/^Search materials: (.+)$/)
  if (match) return `Buscar materiales: ${match[1]}`

  return value
}

export function translateShopText(value: string, language: ShopLanguage): string {
  if (language !== "es") return value
  const leading = value.match(/^\s*/)?.[0] ?? ""
  const trailing = value.match(/\s*$/)?.[0] ?? ""
  const core = value.trim()
  if (!core) return value
  const translated = SPANISH_TEXT[core] ?? translatePattern(core)
  return `${leading}${translated}${trailing}`
}
